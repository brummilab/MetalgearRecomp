#!/usr/bin/env python3
"""
Generate the table of natively available stage overlays.

Usage: gen_overlay_table.py <out.c> <name>... [--recomp <name>...]

The names before --recomp are natively compiled overlays (their chara table
is mgs_ov_<name>), the ones after it overlays recompiled by tools/recomp.py
(rc_overlay_<name>).
"""
import sys


def main():
    out, names = sys.argv[1], sys.argv[2:]
    recomp = []
    if '--recomp' in names:
        i = names.index('--recomp')
        names, recomp = names[:i], names[i + 1:]
    lines = ['/* Generated by port/tools/gen_overlay_table.py - do not edit */',
             '#include "game/game.h"',
             '#include "charadef.h"',
             '#include "native_overlay.h"',
             '#include "../psx/recomp.h"',
             '']
    for n in names:
        lines.append('extern CHARA mgs_ov_%s[];' % n)
    lines += ['', 'const NativeOverlay mgs_native_overlays[] = {']
    for n in names:
        lines.append('    { "%s", mgs_ov_%s },' % (n, n))
    lines += ['    { 0, 0 }', '};', '']
    for n in recomp:
        lines.append('extern const RcOverlay rc_overlay_%s;' % n)
    lines += ['', 'const RecompOverlay mgs_recomp_overlays[] = {']
    for n in recomp:
        lines.append('    { "%s", &rc_overlay_%s },' % (n, n))
    lines += ['    { 0, 0 }', '};', '']
    data = '\n'.join(lines)
    try:
        with open(out) as f:
            if f.read() == data:
                return
    except FileNotFoundError:
        pass
    with open(out, 'w') as f:
        f.write(data)


if __name__ == '__main__':
    main()
