#!/usr/bin/env python3
"""
Derive the native source lists from upstream's psylink command file template
(build/linker_command_file.txt), so the port always follows upstream's layout.

Writes a CMake include file defining
  MGS_MAIN_SOURCES          C files of the main executable
  MGS_OVERLAYS              overlays that are fully decompiled (no INCLUDE_ASM)
  MGS_OVERLAY_<name>        C files of each of those overlays
  MGS_OVERLAYS_INCOMPLETE   overlays that still contain assembly

Usage: gen_sources.py <mgs_reversing_dir> <out.cmake> [FLAG ...]
"""
import os
import re
import sys

from jinja2 import Environment, FileSystemLoader

MARKER = 'OVERLAY CONFIG SECTION'
INCLUDE = re.compile(r'^\s*include\s+"\{\{OBJ_DIR\}\}\\([^"]+)\.obj"?', re.M)
RENDERED_INCLUDE = re.compile(r'^\s*include\s+"@OBJ@\\([^"]+?)\.obj"?', re.M)


def render(template_dir, flags):
    env = Environment(loader=FileSystemLoader(template_dir))
    tpl = env.get_template('linker_command_file.txt')
    return tpl.render(OBJ_DIR='@OBJ@', PSYQ_SDK='', **flags)


def objects(text):
    return [m.group(1).replace('\\', '/') for m in RENDERED_INCLUDE.finditer(text)]


def overlay_names(template_text):
    """Every overlay name tested in the template ({% if OVERLAY == "x" %})."""
    return sorted(set(re.findall(r'OVERLAY\s*==\s*"([a-z0-9_]+)"', template_text)))


def resolve(root, obj):
    c = os.path.join(root, 'source', obj + '.c')
    if os.path.exists(c):
        return c, False
    s = os.path.join(root, 'asm', obj + '.s')
    return s, True


def has_asm(path):
    with open(path, encoding='utf-8', errors='replace') as f:
        return 'INCLUDE_ASM' in f.read()


def cmake_list(name, items):
    body = '\n'.join('    "%s"' % i.replace('\\', '/') for i in items)
    return 'set(%s\n%s\n)\n' % (name, body)


def main():
    root = os.path.abspath(sys.argv[1])
    out = sys.argv[2]
    flags = {f: True for f in sys.argv[3:]} or {'INTEGRAL': True}
    build_dir = os.path.join(root, 'build')
    with open(os.path.join(build_dir, 'linker_command_file.txt'), encoding='utf-8') as f:
        template_text = f.read()

    main_text = render(build_dir, flags).split(MARKER)[0]
    main_sources = []
    for obj in objects(main_text):
        path, is_asm = resolve(root, obj)
        if is_asm:
            sys.exit('gen_sources: main executable still contains assembly: ' + obj)
        main_sources.append(path)
    main_set = set(main_sources)

    complete, incomplete, lists = [], [], {}
    for ov in overlay_names(template_text):
        text = render(build_dir, dict(flags, OVERLAY=ov, OVERLAY_SUFFIX='lhs')).split(MARKER, 1)[1]
        srcs, ok = [], True
        for obj in objects(text):
            path, is_asm = resolve(root, obj)
            if is_asm or has_asm(path):
                ok = False
                break
            if path not in main_set:
                srcs.append(path)
        if ok and srcs:
            complete.append(ov)
            lists[ov] = srcs
        else:
            incomplete.append(ov)

    parts = ['# Generated by port/tools/gen_sources.py - do not edit\n',
             cmake_list('MGS_MAIN_SOURCES', main_sources),
             cmake_list('MGS_OVERLAYS', complete),
             cmake_list('MGS_OVERLAYS_INCOMPLETE', incomplete)]
    for ov in complete:
        parts.append(cmake_list('MGS_OVERLAY_' + ov, lists[ov]))
    data = '\n'.join(parts)
    try:
        with open(out) as f:
            if f.read() == data:
                return
    except FileNotFoundError:
        pass
    with open(out, 'w') as f:
        f.write(data)
    print('gen_sources: %d main sources, %d native overlays, %d incomplete'
          % (len(main_sources), len(complete), len(incomplete)))


if __name__ == '__main__':
    main()
